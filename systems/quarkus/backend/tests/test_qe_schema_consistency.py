def test_the_fallback_derives_the_table_from_the_blueprint():
    sql = schema_sql_from_draft(_draft())

    assert "CREATE TABLE IF NOT EXISTS orders" in sql
    assert "customer_email VARCHAR(255) NOT NULL" in sql
    assert "total_amount NUMERIC(19, 2) NOT NULL" in sql
    assert "items" not in sql, "the fallback still emits the hardcoded table"


def test_the_fallback_covers_every_entity():
    draft = SpecificationDraft.model_validate({
        "serviceName": "shop", "packageName": "com.corp.shop", "basePort": 8080,
        "assumptions": [], "userStories": [],
        "entities": [
            {"name": "Order", "tableName": "orders", "attributes": [
                {"name": "id", "type": "Long", "isPrimaryKey": True}]},
            {"name": "Item", "tableName": "items", "attributes": [
                {"name": "id", "type": "Long", "isPrimaryKey": True}]},
        ],
    })

    sql = schema_sql_from_draft(draft)

    assert "CREATE TABLE IF NOT EXISTS orders" in sql
    assert "CREATE TABLE IF NOT EXISTS items" in sql


def test_an_entity_with_no_attributes_cannot_be_constructed():
    """The contract forbids it, so the defensive branch below is unreachable today.

    Asserted rather than deleted: if the minimum is ever relaxed, the fallback's
    no-columns guard becomes live and this test is where the change shows up.
    """
    from pydantic import ValidationError

    with pytest.raises(ValidationError):
        SpecificationDraft.model_validate({
            "serviceName": "shop", "packageName": "com.corp.shop", "basePort": 8080,
            "assumptions": [], "userStories": [],
            "entities": [{"name": "Empty", "tableName": "empties", "attributes": []}],
        })


def test_a_blueprint_with_no_entities_says_so():
    draft = SpecificationDraft.model_validate({
        "serviceName": "shop", "packageName": "com.corp.shop", "basePort": 8080,
        "assumptions": [], "userStories": [], "entities": [],
    })

    assert "declared no entities" in schema_sql_from_draft(draft)


# ---------------------------------------------------------------------------
# The typo regression: pin the attribute path the pipeline reads
# ---------------------------------------------------------------------------
def test_the_synthesis_response_exposes_the_attributes_the_pipeline_reads():
    """`sqlSchema.schemaDdl`, not `schemaSql`.

    This is the defect that made every project take the fallback: the attribute did
    not exist, a broad `except` swallowed the AttributeError, and silence looked like
    success. Asserting the shape is what stops a rename from reintroducing it.
    """
    response = model_sql_service.synthesize_domain_models_and_sql(
        _draft(), api_key="mock-key", provider="mock",
    )

    assert hasattr(response, "sqlSchema"), "the pipeline reads response.sqlSchema"
    assert hasattr(response.sqlSchema, "schemaDdl")
    assert hasattr(response.sqlSchema, "seedDml")
    assert "CREATE TABLE IF NOT EXISTS orders" in response.sqlSchema.schemaDdl
    assert not hasattr(response, "schemaSql"), (
        "the attribute the pipeline used to read does not exist; if it appears, the "
        "field was renamed and pipeline_runner must be updated in the same change"
    )
